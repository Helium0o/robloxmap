-- every static part is anchored and never fires Touched events, which keeps physics cheap
local function part(parent, size, cf, color, material, shape)
	local p = Instance.new("Part")
	p.Anchored = true
	p.CanTouch = false
	if shape then p.Shape = shape end
	p.Size = size
	p.CFrame = cf
	p.Color = color
	p.Material = material or MAT.SmoothPlastic
	p.TopSurface = Enum.SurfaceType.Smooth
	p.BottomSurface = Enum.SurfaceType.Smooth
	p.Parent = parent
	return p
end

-- road paint and other flat details: no collisions, no shadows, not hit by raycasts
local function mark(parent, size, cf, color)
	local p = part(parent, size, cf, color, MAT.SmoothPlastic)
	p.CanCollide = false
	p.CanQuery = false
	p.CastShadow = false
	return p
end

-- sloped roof half; the slope faces the part's front
local function wedge(parent, size, cf, color, material)
	local w = Instance.new("WedgePart")
	w.Anchored = true
	w.CanTouch = false
	w.Size = size
	w.CFrame = cf
	w.Color = color
	w.Material = material
	w.Parent = parent
	return w
end

-- doors, windows and signs: flush with walls, so they need no collisions or shadows
local function detail(parent, size, cf, color, material)
	local p = part(parent, size, cf, color, material)
	p.CanCollide = false
	p.CastShadow = false
	return p
end

