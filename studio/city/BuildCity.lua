local function crosswalk(nx, nz, dx, dz, sy)
	local rx, rz = -dz, dx
	local s = ROAD / 2 + WALK / 2
	for i = -5, 5, 2 do
		local o = i * 2
		mark(marks, V3(dx ~= 0 and WALK - 1 or 2, 0.1, dx ~= 0 and 2 or WALK - 1), CF(nx + dx * s + rx * o, sy + 0.05, nz + dz * s + rz * o), COL.line)
	end
end

local function stopLine(n, dx, dz, sy)
	local back = ROAD / 2 + (hasCrosswalk(n) and WALK or 2) + 1
	local rx, rz = -dz, dx
	mark(marks, V3(dx ~= 0 and 1 or ROAD / 2 - 1, 0.1, dx ~= 0 and ROAD / 2 - 1 or 1), CF(NODES[n][1] - dx * back + rx * ROAD / 4, sy + 0.05, NODES[n][2] - dz * back + rz * ROAD / 4), COL.line)
end

local function edgeToCity(n, dx, dz)
	-- distance from a city node to the edge of the city, travelling along (dx, dz)
	if dx ~= 0 then return CX / 2 - dx * NODES[n][1] end
	return CZ / 2 - dz * NODES[n][2]
end

