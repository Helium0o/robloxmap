-- flat box between two corners, split into tiles so no part exceeds 2048 studs
local function slab(parent, x0, z0, x1, z1, y0, y1, color, material)
	if x1 - x0 < 0.05 or z1 - z0 < 0.05 then return end
	local nx, nz = math.ceil((x1 - x0) / MAXP), math.ceil((z1 - z0) / MAXP)
	local w, d = (x1 - x0) / nx, (z1 - z0) / nz
	for i = 0, nx - 1 do
		for j = 0, nz - 1 do
			part(parent, V3(w, y1 - y0, d), CF(x0 + w * (i + 0.5), (y0 + y1) / 2, z0 + d * (j + 0.5)), color, material)
		end
	end
end

-- flat strip from A to B (centre line), split when longer than 2048 studs
local function strip(parent, ax, az, bx, bz, width, y, h, color, material, extra, flat)
	local dx, dz = bx - ax, bz - az
	local len = math.sqrt(dx * dx + dz * dz)
	if len < 0.05 then return end
	local total = len + (extra or 0)
	local n = math.ceil(total / MAXP)
	local rot = CFrame.Angles(0, math.atan2(-dz, dx), 0)
	for i = 0, n - 1 do
		local t = (i + 0.5) / n
		local cf = CF(ax + dx * t, y, az + dz * t) * rot
		if flat then mark(parent, V3(total / n, h, width), cf, color) else part(parent, V3(total / n, h, width), cf, color, material) end
	end
end

local function roundedRect(hx, hz, r, n)
	local pts = {}
	local centres = { { hx - r, hz - r }, { -hx + r, hz - r }, { -hx + r, -hz + r }, { hx - r, -hz + r } }
	for k = 0, 3 do
		local c = centres[k + 1]
		for i = 0, n do
			local a = (k + i / n) * math.pi / 2
			table.insert(pts, { c[1] + r * math.cos(a), c[2] + r * math.sin(a) })
		end
	end
	return pts
end

local function cutGaps(pieces, gaps)
	for _, g in ipairs(gaps) do
		local out = {}
		for _, p in ipairs(pieces) do
			local ax, az, bx, bz = p[1], p[2], p[3], p[4]
			if math.abs(ax - bx) < 0.01 and ax >= g[1] and ax <= g[3] then
				local lo, hi = math.min(az, bz), math.max(az, bz)
				if g[4] <= lo or g[2] >= hi then
					table.insert(out, p)
				else
					if g[2] > lo then table.insert(out, { ax, lo, ax, g[2] }) end
					if g[4] < hi then table.insert(out, { ax, g[4], ax, hi }) end
				end
			elseif math.abs(az - bz) < 0.01 and az >= g[2] and az <= g[4] then
				local lo, hi = math.min(ax, bx), math.max(ax, bx)
				if g[3] <= lo or g[1] >= hi then
					table.insert(out, p)
				else
					if g[1] > lo then table.insert(out, { lo, az, g[1], az }) end
					if g[3] < hi then table.insert(out, { g[3], az, hi, az }) end
				end
			else
				table.insert(out, p)
			end
		end
		pieces = out
	end
	return pieces
end

local function ribbon(parent, pts, width, y, h, color, material, gaps, flat)
	local extra = width * math.tan(math.pi / 4 / ARC)
	for i = 1, #pts do
		local a, b = pts[i], pts[i % #pts + 1]
		local pieces = { { a[1], a[2], b[1], b[2] } }
		if gaps then pieces = cutGaps(pieces, gaps) end
		for _, p in ipairs(pieces) do
			strip(parent, p[1], p[2], p[3], p[4], width, y, h, color, material, extra, flat)
		end
	end
end

local function alongPath(pts, spacing, fn)
	local acc = spacing / 2
	for i = 1, #pts do
		local a, b = pts[i], pts[i % #pts + 1]
		local dx, dz = b[1] - a[1], b[2] - a[2]
		local len = math.sqrt(dx * dx + dz * dz)
		local t = acc
		while t < len do
			fn(a[1] + dx * t / len, a[2] + dz * t / len, dx / len, dz / len)
			t += spacing
		end
		acc = t - len
	end
end

