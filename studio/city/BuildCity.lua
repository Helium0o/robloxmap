local function hash2(ix, iz, s)
	local n = ix * 73856093 + iz * 19349663 + s * 83492791
	n = n % 2147483647
	n = (n * 48271) % 2147483647
	n = (n * 48271) % 2147483647
	return n / 2147483647
end
local function vnoise(x, z, scale, s)
	local gx, gz = x / scale, z / scale
	local ix, iz = math.floor(gx), math.floor(gz)
	local fx, fz = gx - ix, gz - iz
	local u, v = fx * fx * (3 - 2 * fx), fz * fz * (3 - 2 * fz)
	local a, b = hash2(ix, iz, s), hash2(ix + 1, iz, s)
	local c, d = hash2(ix, iz + 1, s), hash2(ix + 1, iz + 1, s)
	local top = a + (b - a) * u
	local bot = c + (d - c) * u
	return top + (bot - top) * v
end
local function natural(x, z)
	if HILLS.amp == 0 then return 0 end
	local n = (vnoise(x, z, HILLS.scale, HILLS.seed) - 0.5) * 2 + (vnoise(x, z, HILLS.scale * 0.45, HILLS.seed + 1) - 0.5) * 0.9 + (vnoise(x, z, HILLS.scale * 0.2, HILLS.seed + 2) - 0.5) * 0.4
	return HILLS.amp * n / 1.65
end
local function smoothstep(s) return s * s * (3 - 2 * s) end
local function cellRange(lo, hi, g, n)
	return math.max(0, math.floor((lo + g) / CELL)), math.min(n - 1, math.floor((hi + g) / CELL))
end

