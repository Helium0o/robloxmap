	for _, k in ipairs({ 1, 3 }) do
		local b = LINKS[a][k]
		if b ~= 0 then
			local ax, az = NODES[a][1], NODES[a][2]
			local dx, dz = DX[k], DZ[k]
			local rx, rz = -dz, dx
			local len = math.abs(NODES[b][1] - ax) + math.abs(NODES[b][2] - az)
			local ca, cb = NODES[a][4] == 1, NODES[b][4] == 1
			local sy = (ca and cb) and 0 or 0.2
			if not (ca and cb) then
				local s0, s1 = -ROAD / 2, len + ROAD / 2
				if ca then s0 = edgeToCity(a, dx, dz) end
				if cb then s1 = len - edgeToCity(b, -dx, -dz) end
				strip(roads, ax + dx * s0, az + dz * s0, ax + dx * s1, az + dz * s1, ROAD, -0.4, 1.2, COL.asphalt, MAT.Asphalt)
			end
			local ma = ROAD / 2 + (hasCrosswalk(a) and WALK or 0) + 2
			local mb = ROAD / 2 + (hasCrosswalk(b) and WALK or 0) + 2
			for _, o in ipairs({ -0.45, 0.45 }) do
				strip(marks, ax + dx * ma + rx * o, az + dz * ma + rz * o, ax + dx * (len - mb) + rx * o, az + dz * (len - mb) + rz * o, 0.4, sy + 0.05, 0.1, COL.yellow, nil, 0, true)
			end
			if hasCrosswalk(a) then crosswalk(ax, az, dx, dz, sy) end
			if hasCrosswalk(b) then crosswalk(NODES[b][1], NODES[b][2], -dx, -dz, sy) end
			if mustStop(b, k) then stopLine(b, dx, dz, sy) end
			if mustStop(a, OPP[k]) then stopLine(a, -dx, -dz, sy) end
		end
	end
end

