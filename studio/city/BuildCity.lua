-- a straight piece of road, kerb or barrier between two points, tilted to follow the slope;
-- its top sits "lift" studs above the line
local function seg3(parent, p, q, width, thick, lift, color, material, extra, flat)
	local a = V3(p[1], p[2] + lift, p[3])
	local b = V3(q[1], q[2] + lift, q[3])
	local len = (b - a).Magnitude
	if len < 0.05 then return end
	if len > 2000 then
		local m = { (p[1] + q[1]) / 2, (p[2] + q[2]) / 2, (p[3] + q[3]) / 2 }
		seg3(parent, p, m, width, thick, lift, color, material, extra, flat)
		seg3(parent, m, q, width, thick, lift, color, material, extra, flat)
		return
	end
	local cf = CFrame.lookAt((a + b) / 2, b) * CF(0, -thick / 2, 0)
	local size = V3(width, thick, len + (extra or 0))
	if flat then return mark(parent, size, cf, color) end
	return part(parent, size, cf, color, material)
end

