end

local function stampSeg(px, py, pz, qx, qy, qz, half, margin, mat)
	local R = half + margin
	local i0, i1 = cellRange(math.min(px, qx) - R, math.max(px, qx) + R, GX, NXC)
	local j0, j1 = cellRange(math.min(pz, qz) - R, math.max(pz, qz) + R, GZ, NZC)
	local dx, dz = qx - px, qz - pz
	local L2 = dx * dx + dz * dz
	for j = j0, j1 do
		local z = -GZ + CELL * j + 2
		for i = i0, i1 do
			local x = -GX + CELL * i + 2
			local t = L2 > 0 and ((x - px) * dx + (z - pz) * dz) / L2 or 0
			if t < 0 then t = 0 elseif t > 1 then t = 1 end
			local ex, ez = px + dx * t - x, pz + dz * t - z
			local d = math.sqrt(ex * ex + ez * ez)
			if d <= R then
				local w = d <= half and 1 or smoothstep(1 - (d - half) / margin)
				local k = j * NXC + i + 1
				if w > WGT[k] then
					WGT[k] = w
					TGT[k] = py + (qy - py) * t
				end
				if d <= half and mat > 0 then TMAT[k] = mat end
			end
		end
	end
end

local function stampPad(cx, cz, hw, hd, rot, y, mat, margin)
	local t = -rot * math.pi / 180
	local ux, uz, vx, vz = math.cos(t), -math.sin(t), math.sin(t), math.cos(t)
	local R = math.sqrt(hw * hw + hd * hd) + margin
	local i0, i1 = cellRange(cx - R, cx + R, GX, NXC)
	local j0, j1 = cellRange(cz - R, cz + R, GZ, NZC)
	for j = j0, j1 do
		local z = -GZ + CELL * j + 2
		for i = i0, i1 do
			local x = -GX + CELL * i + 2
			local dx, dz = x - cx, z - cz
			local lx, lz = dx * ux + dz * uz, dx * vx + dz * vz
			local ex, ez = math.max(0, math.abs(lx) - hw), math.max(0, math.abs(lz) - hd)
			local d = math.sqrt(ex * ex + ez * ez)
			if d <= margin then
				local w = d == 0 and 1 or smoothstep(1 - d / margin)
				local k = j * NXC + i + 1
				if w > WGT[k] then
					WGT[k] = w
					TGT[k] = y
				end
				if d == 0 and mat > 0 then TMAT[k] = mat end
			end
		end
	end
end

