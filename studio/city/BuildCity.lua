-- ring highway ------------------------------------------------------------------------------------------
if SETTINGS.highway and #HWY_Y > 0 then
	local hwy = folder("Highway")
	local function ring(o)
		local r = ringPoints(RING.rx + o, RING.rz + o, RING.rc + o)
		for i, p in ipairs(r) do r[i] = { p[1], HWY_Y[i], p[2] } end
		return r
	end
	local function cutGaps(pieces, gaps)
		for _, g in ipairs(gaps) do
			local out = {}
			for _, p in ipairs(pieces) do
				local ax, az, ay, bx, bz, by = table.unpack(p)
				local t0, t1
				if math.abs(ax - bx) < 0.01 and ax >= g[1] and ax <= g[3] and math.abs(bz - az) > 0.01 then
					t0, t1 = (g[2] - az) / (bz - az), (g[4] - az) / (bz - az)
				elseif math.abs(az - bz) < 0.01 and az >= g[2] and az <= g[4] and math.abs(bx - ax) > 0.01 then
					t0, t1 = (g[1] - ax) / (bx - ax), (g[3] - ax) / (bx - ax)
				end
				if not t0 then
					table.insert(out, p)
				else
					if t0 > t1 then t0, t1 = t1, t0 end
					t0, t1 = math.max(0, t0), math.min(1, t1)
					if t0 >= t1 then
						table.insert(out, p)
					else
						if t0 > 0 then table.insert(out, { ax, az, ay, ax + (bx - ax) * t0, az + (bz - az) * t0, ay + (by - ay) * t0 }) end
						if t1 < 1 then table.insert(out, { ax + (bx - ax) * t1, az + (bz - az) * t1, ay + (by - ay) * t1, bx, bz, by }) end
					end
				end
			end
			pieces = out
		end
		return pieces
	end
	local function ribbon(pts, width, thick, lift, color, material, gaps, flat)
		for i = 1, #pts do
			local a, b = pts[i], pts[i % #pts + 1]
			local pieces = { { a[1], a[3], a[2], b[1], b[3], b[2] } }
			if gaps then pieces = cutGaps(pieces, gaps) end
			for _, q in ipairs(pieces) do
				seg3(hwy, { q[1], q[3], q[2] }, { q[4], q[6], q[5] }, width, thick, lift, color, material, width * 0.12, flat)
			end
		end
	end
	local gaps = {}
	for _, r in ipairs(RAMPS) do
		local x, zh = r[1], r[3]
		local side = x > 0 and 1 or -1
		local dir = zh > r[2] and 1 or -1
		local bx = x - side * 7.75
		table.insert(gaps, { bx - 2, math.min(zh, zh + dir * 70), bx + 2, math.max(zh, zh + dir * 70) })
	end
	local centre = ring(0)
	ribbon(centre, DECK, 2, TOP, COL.asphalt, MAT.Asphalt)
	ribbon(ring(DECK / 2 - 0.75), 1.5, 3, TOP + 3, COL.barrier, MAT.Concrete, gaps)
	ribbon(ring(-DECK / 2 + 0.75), 1.5, 3, TOP + 3, COL.barrier, MAT.Concrete)
	ribbon(centre, 2, 3, TOP + 3, COL.barrier, MAT.Concrete)
	if SETTINGS.roadMarkings then
		for _, o in ipairs({ -15, 15 }) do ribbon(ring(o), 0.5, 0.1, TOP + 0.06, COL.line, nil, nil, true) end
	end
	local function underRoad(x, z)
		for _, sx in ipairs(SPOKE_X) do
			if math.abs(x - sx) < AVE + 8 and math.abs(z) > CZ / 2 then return true end
		end
		for _, sz in ipairs(SPOKE_Z) do
			if math.abs(z - sz) < AVE + 8 and math.abs(x) > CX / 2 then return true end
		end
		return false
	end
	local function along(pts, spacing, fn)
		local acc = spacing / 2
		for i = 1, #pts do
			local a, b = pts[i], pts[i % #pts + 1]
			local dx, dz = b[1] - a[1], b[3] - a[3]
			local len = math.sqrt(dx * dx + dz * dz)
			local t = acc
			while t < len do
				local f = t / len
				fn(a[1] + dx * f, a[2] + (b[2] - a[2]) * f, a[3] + dz * f, dx / len, dz / len)
				t += spacing
			end
			acc = t - len
		end
	end
	along(centre, 64, function(x, y, z, hx, hz)
		local ground = heightAt(x, z)
		if underRoad(x, z) or y - ground < 8 then return end
		part(hwy, V3(6, y - ground + 1, 6), CF(x, (y - 3 + ground - 4) / 2, z), COL.concrete, MAT.Concrete)
		part(hwy, V3(5, 3, DECK - 8), CF(x, y - 3, z) * CFrame.Angles(0, math.atan2(-hz, hx), 0), COL.concrete, MAT.Concrete)
	end)
	along(centre, 130, function(x, y, z, hx, hz)
		local turn = CFrame.Angles(0, math.atan2(-hz, hx), 0)
		part(hwy, V3(0.8, 14, 0.8), CF(x, y + TOP + 7, z), COL.pole, MAT.Metal)
