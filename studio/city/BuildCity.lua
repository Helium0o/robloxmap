	for _, lamp in ipairs(CollectionService:GetTagged("CityTrafficLamp")) do
		local n, axis, l = lamp:GetAttribute("Node"), lamp:GetAttribute("Axis"), lamp:GetAttribute("Light")
		if n and NODES[n] then
